// rust/emit_rust.c — weftc-codegen backend: Rust zero-copy projection crates
// (target rust).
//
// Guarantees for every verified struct:
//   * #[repr(C)] (+ #[repr(align(N))] when the IR demands it) — byte-identical
//     with the C header and the byte-exact GPU structs
//   * no_std, zero dependencies: the emitted module uses `core` only
//     (Law 2) — it compiles for bare-metal, MCU and kernel targets
//   * zero-allocation projection API: from_bytes / from_bytes_mut return &Self
//     views after validating length, alignment and the schema hash header
//     (Law 1); read_packed / write_packed use core::ptr::{read,write}_unaligned
//     for alignment-free by-value projection (Law 3)
//   * optional bytemuck (Pod/Zeroable) and zerocopy (0.8 trio) impls behind
//     cargo features — never compiled unless the consumer opts in
//   * zero-overhead const-fn mutation builders + bitfield accessors
//
// The shared core module (error enum + f16 codec) is emitted once per
// generation run; every struct module references it as a sibling
// (`super::weft_projection_core`) — the flat layout the test harness mounts.

#include "../weftc_codegen.h"

static const char* rs_scalar_type(weft_type_kind k, bool* uses_f16)
{
    switch (k) {
    case WT_U8: return "u8";
    case WT_I8: return "i8";
    case WT_U16: return "u16";
    case WT_I16: return "i16";
    case WT_U32: return "u32";
    case WT_I32: return "i32";
    case WT_U64: return "u64";
    case WT_I64: return "i64";
    case WT_F16: *uses_f16 = true; return "WeftF16";
    case WT_F32: return "f32";
    case WT_F64: return "f64";
    case WT_BOOL: return "bool";
    default: return "?";
    }
}

// full Rust type text for a field, e.g. "[f32; 3]" / "AxisSample"
static void rs_field_type(const weft_field* f, char out[176], bool* uses_f16, bool* uses_super)
{
    switch (f->kind) {
    case WT_VEC2F32: strcpy(out, "[f32; 2]"); break;
    case WT_VEC3F32: strcpy(out, "[f32; 3]"); break;
    case WT_VEC4F32: strcpy(out, "[f32; 4]"); break;
    case WT_VEC2F16: *uses_f16 = true; strcpy(out, "[WeftF16; 2]"); break;
    case WT_VEC3F16: *uses_f16 = true; strcpy(out, "[WeftF16; 3]"); break;
    case WT_VEC4F16: *uses_f16 = true; strcpy(out, "[WeftF16; 4]"); break;
    case WT_ARRAY: {
        weft_field tmp = *f;
        tmp.kind = f->elem_kind;
        char elem[176];
        rs_field_type(&tmp, elem, uses_f16, uses_super);
        snprintf(out, 176, "[%.150s; %u]", elem, f->count);
        break;
    }
    case WT_STRUCT:
        *uses_super = true;
        snprintf(out, 128, "%s", f->struct_type->rust_name);
        break;
    default:
        snprintf(out, 128, "%s", rs_scalar_type(f->kind, uses_f16));
        break;
    }
}

// hex with underscores: 0x8F4C_1120_A9B3_0012
static void rs_hex64(uint64_t v, char out[32])
{
    snprintf(out, 32, "0x%04X_%04X_%04X_%04X",
             (unsigned)(v >> 48) & 0xFFFFu, (unsigned)(v >> 32) & 0xFFFFu,
             (unsigned)(v >> 16) & 0xFFFFu, (unsigned)v & 0xFFFFu);
}

static void rs_hex32(uint32_t v, char out[24])
{
    snprintf(out, 24, "0x%04X_%04X", (v >> 16) & 0xFFFFu, v & 0xFFFFu);
}

